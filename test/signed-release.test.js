'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { assertSigningEnvironment } = require('../scripts/signing-preflight');
const root = path.resolve(__dirname, '..');
const policyFile = path.join(root, 'src/update-security.json');
const pkg = require('../package.json');
const policy = JSON.parse(fs.readFileSync(policyFile, 'utf8'));
assert.equal(policy.enabled, false, 'O código-fonte nunca pode vir com instalação automática autorizada.');
assert.ok(!String(policy.publisherName).trim(), 'O template não deve fixar identidade falsa de certificado.');
assert.throws(() => assertSigningEnvironment({}), /não configurada/i);
assert.throws(() => assertSigningEnvironment({ EDGE_SIGN_CERT_NAME: 'Fake', EDGE_SIGN_PUBLISHER: 'Fake' }), /subject/i);
assert.deepEqual(assertSigningEnvironment({ EDGE_SIGN_CERT_NAME: 'Example', EDGE_SIGN_PUBLISHER: 'CN=Example, O=Example, C=BR' }),
  { certName: 'Example', publisherName: 'CN=Example, O=Example, C=BR' });
assert.equal(pkg.build.win.target[0].target, 'nsis');
assert.equal(pkg.build.publish[0].provider, 'github');
const workflow = fs.readFileSync(path.join(root,'.github/workflows/windows-signed-candidate.yml'),'utf8');
assert.match(workflow, /workflow_dispatch:/);
assert.doesNotMatch(workflow, /\n  push:/, 'Nunca construir automaticamente com chave de produção em push.');
assert.doesNotMatch(workflow, /\n  pull_request:/, 'Nunca expor chave de assinatura a PR.');
assert.match(workflow, /environment: signed-release/);
assert.match(workflow, /runs-on: \[self-hosted, windows, x64, code-signing\]/);
assert.doesNotMatch(workflow, /gh release create|--publish always/, 'Não publicar automaticamente.');
const configFile = path.join(root, 'scripts/signed-builder.config.cjs');
const env = { ...process.env, EDGE_SIGN_CERT_NAME: 'Example', EDGE_SIGN_PUBLISHER: 'CN=Example, O=Example, C=BR' };
const good = spawnSync(process.execPath, [configFile], { env, cwd: root, encoding: 'utf8' });
assert.equal(good.status, 0, good.stderr);
const output = JSON.parse(good.stdout);
assert.equal(output.forceCodeSigning, true);
assert.equal(output.verifyUpdateCodeSignature, true);
assert.equal(output.publisherName, env.EDGE_SIGN_PUBLISHER);
const bad = spawnSync(process.execPath, [configFile], { env: { ...process.env, EDGE_SIGN_CERT_NAME: '', EDGE_SIGN_PUBLISHER: '' }, cwd: root, encoding: 'utf8' });
assert.notEqual(bad.status, 0, 'A compilação assinada deve falhar sem identidade.');
assert.equal(JSON.parse(fs.readFileSync(policyFile,'utf8')).enabled, false, 'Nenhum teste pode ligar o updater local.');
console.log('OK: release exige identidade real, assinatura obrigatória, CI manual e perfil seguro por padrão.');
